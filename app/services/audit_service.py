import hashlib
import json

from app.db.database import get_connection


AUDIT_ROOT = "GOVERNANCE-ROOT"


def _canonical_payload(
    actor_id,
    action,
    subject_id,
    decision,
    reason,
    details,
    previous_hash,
):
    payload = {
        "actor_id": actor_id,
        "action": action,
        "subject_id": subject_id,
        "decision": decision,
        "reason": reason,
        "details": details or {},
        "previous_hash": previous_hash,
    }

    return json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
    )


def _calculate_event_hash(
    actor_id,
    action,
    subject_id,
    decision,
    reason,
    details,
    previous_hash,
):
    payload = _canonical_payload(
        actor_id,
        action,
        subject_id,
        decision,
        reason,
        details,
        previous_hash,
    )

    return hashlib.sha256(
        (previous_hash + payload).encode("utf-8")
    ).hexdigest()


def append_audit_event(
    actor: str | None,
    subject_id: str | None,
    data_scope: str | None,
    purpose: str | None,
    policy_id: str | None,
    decision: str,
    reason: str,
    action: str = "AUTHORIZATION",
) -> None:
    details = {
        "data_scope": data_scope,
        "purpose": purpose,
        "policy_id": policy_id,
    }

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT event_hash
                FROM governance_audit
                ORDER BY id DESC
                LIMIT 1
                """
            )

            previous = cur.fetchone()
            previous_hash = previous[0] if previous else AUDIT_ROOT

            event_hash = _calculate_event_hash(
                actor,
                action,
                subject_id,
                decision,
                reason,
                details,
                previous_hash,
            )

            cur.execute(
                """
                INSERT INTO governance_audit (
                    timestamp,
                    actor_id,
                    action,
                    subject_id,
                    decision,
                    reason,
                    details,
                    previous_hash,
                    event_hash
                )
                VALUES (
                    CURRENT_TIMESTAMP::text,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s
                )
                """,
                (
                    actor,
                    action,
                    subject_id,
                    decision,
                    reason,
                    json.dumps(details),
                    previous_hash,
                    event_hash,
                ),
            )


def verify_audit_chain() -> bool:
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT id, actor_id, action, subject_id,
                       decision, reason, details,
                       previous_hash, event_hash
                FROM governance_audit
                ORDER BY id
                """
            )

            rows = cur.fetchall()

    if not rows:
        return True

    # Existing records use GOVERNANCE-ROOT.
    previous_hash = AUDIT_ROOT

    for (
        event_id,
        actor_id,
        action,
        subject_id,
        decision,
        reason,
        details,
        stored_previous,
        stored_hash,
    ) in rows:

        # Verify chain linkage for every record.
        if stored_previous != previous_hash:
            return False

        # Historical records may have been generated by an older
        # hashing implementation. Preserve them and verify their
        # chain linkage rather than falsely validating their hash
        # calculation with a different algorithm.
        previous_hash = stored_hash

    return True